#!/usr/bin/env python3
"""Render the pregnancy guidance content as a readable reference.

Usage: ./scripts/render-pregnancy-reference.py [--check]

Reads src/Balsm.API/Content/pregnancy-weeks.v1.json (the source of truth the
API serves) and writes docs/content/pregnancy-weeks/reference.md: every week in
English and Arabic, with its symptoms, tests, danger signs and the sources it
cites, for clinical review. Never hand-edit the output; edit the JSON and
re-run. --check exits non-zero when the reference is out of date.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONTENT = ROOT / "src/Balsm.API/Content/pregnancy-weeks.v1.json"
OUT = ROOT / "docs/content/pregnancy-weeks/reference.md"


def cell(text):
    return (text or "—").replace("|", "\\|").replace("\n", " ")


def bilingual(lines, label, text):
    lines.append(f"| {label} | {cell(text['en'])} | <div dir=\"rtl\">{cell(text['ar'])}</div> |")


def keyed(lines, label, keys, table):
    for i, key in enumerate(keys):
        bilingual(lines, label if i == 0 else "", table[key])


def render(d):
    sources = {s["id"]: s for s in d["sources"]}
    lines = [
        "<!-- Generated by scripts/render-pregnancy-reference.py from",
        "     src/Balsm.API/Content/pregnancy-weeks.v1.json. Do not edit by hand. -->",
        "",
        "# Pregnancy weekly guidance — content reference",
        "",
        f"Content version **`{d['version']}`** · {len(d['weeks'])} weeks · {len(d['sources'])} sources.",
        "",
        f"> {d['disclaimer']['en']} {d['source']['en']}.",
        ">",
        f"> {d['multiples_note']['en']}",
        "",
        "Served by `GET /api/v1/content/pregnancy-weeks?lang=en|ar`. See [README](README.md) for how to change it.",
        "",
        "## Weeks",
        "",
        " · ".join(f"[{w['week']}](#week-{w['week']})" for w in d["weeks"]),
        "",
    ]

    for w in d["weeks"]:
        baby, size = w["baby"], w["baby"]["fetal_size"]
        figures = [
            f"{size['length_mm']} mm" if size.get("length_mm") is not None else None,
            f"{size['weight_g']} g" if size.get("weight_g") is not None else None,
        ]
        lines += [
            f"### Week {w['week']}",
            "",
            "| | English | العربية |",
            "|---|---|---|",
        ]
        bilingual(lines, "Title", w["title"])
        bilingual(lines, "Summary", w["summary"])
        bilingual(lines, "Feelings", w["feelings"])
        for i, tip in enumerate(w["tips"]):
            bilingual(lines, "Tips" if i == 0 else "", tip)
        bilingual(lines, "Baby", baby["fact"])
        if size.get("comparison"):
            bilingual(lines, "Size of", size["comparison"])
        keyed(lines, "Symptoms", w["symptoms"], {k: v["label"] for k, v in d["symptom_guide"].items()})
        keyed(lines, "Tests due", w["tests_due"], d["test_labels"])
        keyed(lines, "Danger signs", w["danger_signs"], d["danger_sign_labels"])
        keyed(lines, "Topics", w["topics"], d["topic_labels"])
        lines.append("")
        if any(figures):
            lines.append(f"Size: {' · '.join(f for f in figures if f)}  ")
        if baby.get("media"):
            media = baby["media"]
            files = " · ".join(
                f"[{', '.join(r['when'].values()) or 'default'}]({r['url']}) {r['width']}×{r['height']}, {r['bytes'] // 1024} KB"
                for r in media["renditions"]
            )
            lines.append(f"Illustration: {files} ({media['credit']}, [source]({media['source_url']}))  ")
        lines.append("Sources: " + ", ".join(f"[{s}](#src-{s})" for s in w["sources"]))
        lines.append("Baby sources: " + ", ".join(f"[{s}](#src-{s})" for s in baby["sources"]))
        lines.append("")

    lines += [
        "## Symptom guide",
        "",
        "| Symptom | What helps | Call the doctor if | Sources |",
        "|---|---|---|---|",
    ]
    for key, s in d["symptom_guide"].items():
        call = s.get("call_doctor_if")
        lines.append(
            f"| **{cell(s['label']['en'])}** (`{key}`)<br><div dir=\"rtl\">{cell(s['label']['ar'])}</div> "
            f"| {cell(s['self_care']['en'])}<br><div dir=\"rtl\">{cell(s['self_care']['ar'])}</div> "
            f"| {cell(call['en']) if call else '—'}<br><div dir=\"rtl\">{cell(call['ar']) if call else ''}</div> "
            f"| {', '.join(s['sources'])} |"
        )

    for title, table in [
        ("Danger signs", d["danger_sign_labels"]),
        ("Tests", d["test_labels"]),
        ("Topics", d["topic_labels"]),
    ]:
        lines += ["", f"## {title}", "", "| Key | English | العربية |", "|---|---|---|"]
        lines += [f"| `{k}` | {cell(v['en'])} | <div dir=\"rtl\">{cell(v['ar'])}</div> |" for k, v in table.items()]

    lines += ["", "## Sources", "", "| Id | Title | Publisher | Accessed |", "|---|---|---|---|"]
    for s in sources.values():
        lines.append(
            f"| <a id=\"src-{s['id']}\"></a>`{s['id']}` | [{cell(s['title'])}]({s['url']}) "
            f"| {cell(s['publisher'])} | {s['accessed']} |"
        )

    lines += ["", "## Illustration credits", ""]
    lines += [f"- `{k}`: {c['text']['en']} — [{c['license']}]({c['license_url']})" for k, c in d["illustration_credits"].items()]
    return "\n".join(lines) + "\n"


def main():
    text = render(json.loads(CONTENT.read_text(encoding="utf-8")))
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print(f"{OUT.relative_to(ROOT)} is out of date; run scripts/render-pregnancy-reference.py", file=sys.stderr)
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
